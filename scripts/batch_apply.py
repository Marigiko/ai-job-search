def escape_latex(text: str) -> str:
    """Escape special LaTeX characters in text."""
    # Use a placeholder for backslash to avoid double-escaping
    text = text.replace('\x00', '')  # remove any null chars first
    # Replace backslash with placeholder first, then restore at the end
    text = text.replace('\\', '\x00BS\x00')
    replacements = [
        ('%', r'\%'),
        ('&', r'\&'),
        ('_', r'\_'),
        ('#', r'\#'),
        ('$', r'\$'),
        ('{', r'\{'),
        ('}', r'\}'),
        ('~', r'\textasciitilde{}'),
        ('^', r'\textasciicircum{}'),
    ]
    for char, replacement in replacements:
        text = text.replace(char, replacement)
    # Restore backslash last
    text = text.replace('\x00BS\x00', r'\textbackslash{}')
    return text



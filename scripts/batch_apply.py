def compile_cv(tex_path: Path) -> Path:
    """Compile CV with lualatex. Returns PDF path."""
    pdf_path = tex_path.with_suffix(".pdf")
    result = subprocess.run(
        ["lualatex", "-interaction=nonstopmode", tex_path.name],
        cwd=tex_path.parent,
        capture_output=True,
        text=True,
        timeout=120,
    )
    if result.returncode != 0:
        print(f"  [WARN] lualatex returned {result.returncode} for {tex_path.name}")
        print(f"  stderr: {result.stderr[-500:]}")
    return pdf_path


def compile_cover(tex_path: Path) -> Path:
    """Compile cover letter with xelatex. Returns PDF path."""
    pdf_path = tex_path.with_suffix(".pdf")
    result = subprocess.run(
        ["xelatex", "-interaction=nonstopmode", tex_path.name],
        cwd=tex_path.parent,
        capture_output=True,
        text=True,
        timeout=120,
    )
    if result.returncode != 0:
        print(f"  [WARN] xelatex returned {result.returncode} for {tex_path.name}")
        print(f"  stderr: {result.stderr[-500:]}")
    return pdf_path


def send_application(to_email: str, cv_pdf: Path, cover_pdf: Path, job: dict) -> bool:
    """Send application email with CV + cover letter attached."""
    password = os.getenv("GMAIL_APP_PASSWORD")
    if not password:
        raise ValueError("GMAIL_APP_PASSWORD not set in .env")

    company = job.get("company", "the team")
    role = job.get("title", "Developer")

    msg = MIMEMultipart()
    msg["From"] = SENDER
    msg["To"] = to_email
    msg["Subject"] = f"Postulacion: {role} — Mario Aquino"

    body = f"""Estimado equipo,

Adjunto mi CV y carta de presentacion para la posicion.

Quedo a disposicion para conversar.

Saludos cordiales,
{CANDIDATE['name']}
{CANDIDATE['email']}
{CANDIDATE['phone']}
{CANDIDATE['linkedin']}
"""
    msg.attach(MIMEText(body, "plain"))

    for pdf_path in [cv_pdf, cover_pdf]:
        if pdf_path.exists():
            with open(pdf_path, "rb") as f:
                part = MIMEBase("application", "octet-stream")
                part.set_payload(f.read())
            encoders.encode_base64(part)
            part.add_header("Content-Disposition", f"attachment; filename={pdf_path.name}")
            msg.attach(part)

    with smtplib.SMTP("smtp.gmail.com", 587) as server:
        server.ehlo()
        server.starttls()
        server.login(SENDER, password)
        server.send_message(msg)

    return True


def load_sent_log() -> dict:
    """Load sent log to avoid duplicates."""
    if SENT_LOG.exists():
        return json.loads(SENT_LOG.read_text(encoding="utf-8"))
    return {}


def save_sent_log(log: dict):
    """Save sent log."""
    SENT_LOG.parent.mkdir(parents=True, exist_ok=True)
    SENT_LOG.write_text(json.dumps(log, ensure_ascii=False, indent=2), encoding="utf-8")


def main():
    ap = argparse.ArgumentParser(description="Batch application generator + sender")
    ap.add_argument("--jobs", required=True, help="Path to jobs JSON file")
    ap.add_argument("--dry-run", action="store_true", help="Generate only, do not send")
    ap.add_argument("--send", action="store_true", help="Generate and send emails")
    ap.add_argument("--delay", type=int, default=3, help="Delay between emails in minutes (default 3)")
    ap.add_argument("--limit", type=int, default=0, help="Max jobs to process (0=all)")
    ap.add_argument("--offset", type=int, default=0, help="Skip first N jobs")
    args = ap.parse_args()

    jobs_path = Path(args.jobs)
    if not jobs_path.exists():
        print(f"[!] Jobs file not found: {jobs_path}")
        sys.exit(1)

    jobs_data = json.loads(jobs_path.read_text(encoding="utf-8"))
    jobs = jobs_data if isinstance(jobs_data, list) else jobs_data.get("jobs", [])

    if args.offset:
        jobs = jobs[args.offset:]
    if args.limit:
        jobs = jobs[:args.limit]

    sent_log = load_sent_log()
    print(f"\n{'='*60}")
    print(f"BATCH APPLY — {len(jobs)} jobs")
    print(f"Mode: {'DRY RUN' if args.dry_run else 'SEND'}")
    print(f"{'='*60}\n")

    sent_count = 0
    for i, job in enumerate(jobs, 1):
        email = job.get("apply_email", "")
        company = job.get("company", "Unknown")
        role = job.get("title", "Developer")

        if not email:
            print(f"[{i}/{len(jobs)}] SKIP {company} — no email")
            continue

        # Dedup check
        if email in sent_log:
            print(f"[{i}/{len(jobs)}] SKIP {company} — already sent to {email}")
            continue

        print(f"\n[{i}/{len(jobs)}] Processing: {role} @ {company} -> {email}")

        # Generate filenames
        safe_name = "".join(c if c.isalnum() else "_" for c in f"{company}_{role}").lower()[:50]
        cv_tex = CV_DIR / f"main_{safe_name}.tex"
        cover_tex = COVER_DIR / f"cover_{safe_name}.tex"

        # Generate tex files
        generate_cv_tex(job, cv_tex)
        generate_cover_tex(job, cover_tex)
        print(f"  Generated: {cv_tex.name}, {cover_tex.name}")

        # Compile
        cv_pdf = compile_cv(cv_tex)
        cover_pdf = compile_cover(cover_tex)

        if not cv_pdf.exists():
            print(f"  [ERROR] CV PDF not generated, skipping")
            continue
        if not cover_pdf.exists():
            print(f"  [ERROR] Cover PDF not generated, skipping")
            continue

        print(f"  Compiled: {cv_pdf.name} ({cv_pdf.stat().st_size//1024}KB), {cover_pdf.name} ({cover_pdf.stat().st_size//1024}KB)")

        if args.dry_run:
            print(f"  -> DRY RUN (not sent)")
            continue

        # Send
        try:
            send_application(email, cv_pdf, cover_pdf, job)
            sent_log[email] = {
                "company": company,
                "role": role,
                "date": time.strftime("%Y-%m-%d %H:%M"),
            }
            save_sent_log(sent_log)
            sent_count += 1
            print(f"  -> SENT ({sent_count} total)")
        except Exception as e:
            print(f"  [ERROR] Send failed: {e}")
            continue

        # Rate limiting
        if i < len(jobs) and sent_count > 0:
            delay_secs = random.randint(args.delay * 60, args.delay * 60 + 120)
            print(f"  Waiting {delay_secs//60}m {delay_secs%60}s...")
            time.sleep(delay_secs)

    print(f"\n{'='*60}")
    print(f"DONE — {sent_count} applications sent")
    print(f"{'='*60}")


if __name__ == "__main__":
    main()
